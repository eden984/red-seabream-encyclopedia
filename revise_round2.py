# 4장 그림 새로 그림: 고정식(줄이 헤드 위에 묶임) / 유동식(줄이 헤드를 관통, 헤드가 미끄러짐) / 텅스텐(작은 헤드, 관통)
A = 'class="d" fill="none" stroke="#111" stroke-linecap="round" stroke-linejoin="round"'
T = 'class="t" font-size="15" fill="#111" stroke="none" text-anchor="middle"'
def head(cx, cy, r, through):
    s = f'<path {A} stroke-width="2" d="M{cx-r} {cy} a{r} {r} 0 1 0 {2*r} 0 a{r} {r} 0 1 0 {-2*r} 0"/>'
    for k in range(-r + 4, r - 2, 5):  # 해칭
        h = (r * r - k * k) ** 0.5 * 0.8
        s += f'<path {A} stroke-width=".8" d="M{cx-h:.1f} {cy+k} L{cx+h:.1f} {cy+k-4}"/>'
    if through:  # 관통 구멍
        s += f'<path {A} stroke-width="1" stroke-dasharray="2 3" d="M{cx} {cy-r} L{cx} {cy+r}"/>'
    return s
def skirt(cx, top, n=5):
    return "".join(f'<path {A} stroke-width="1" d="M{cx} {top} q{(i-2)*3} 14 {(i-2)*7} 30"/>' for i in range(n))
def hook(cx, top):
    return f'<path {A} stroke-width="1.6" d="M{cx} {top} l0 22 q0 10 -8 10 q-7 0 -7 -7 M{cx-15} {top+25} l-3 -4"/>'
